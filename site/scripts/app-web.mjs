// Copies the Ark's embed page and every file it loads from the site's build into crates/app/web/,
// which the Mac app embeds and serves offline in its webview (crates/app/src/webview.rs).
//
//   npm run build && node scripts/app-web.mjs
//
// It starts from the prerendered page and follows the build's Vite manifest: each file's imports,
// dynamic imports and styles, then the fonts and images those name. Of SvelteKit's route nodes it
// takes the page's own and the root error page's (node 1), which the client loads before it
// hydrates any page; the app never navigates to another route.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const client = join(site, '.svelte-kit/output/client');
const pages = join(site, '.svelte-kit/output/prerendered/pages');
const out = join(site, '../crates/app/web');
const PAGE = 'ark-of-the-covenant/embed.html';

if (!existsSync(join(pages, PAGE))) {
	console.error(`No ${PAGE} in the build: run npm run build first.`);
	process.exit(1);
}
const manifest = JSON.parse(readFileSync(join(client, '.vite/manifest.json'), 'utf8'));
const byFile = new Map(Object.values(manifest).map((m) => [m.file, m]));

const html = readFileSync(join(pages, PAGE), 'utf8');
/** Paths from the site's root, without the leading slash. */
const files = new Set([PAGE]);
const pending = [...html.matchAll(/(?:\.\.\/)+(_app\/immutable\/[^"'\s)]+)/g)].map((m) => m[1]);
// The page's own nodes, as SvelteKit's boot script names them, and the root layout's and error
// page's (0 and 1), which start() imports before it hydrates.
for (const [key, m] of Object.entries(manifest)) if (/\/nodes\/[01]\.js$/.test(key)) pending.push(m.file);
const nodes = new Set(pending.filter((f) => f.includes('/nodes/')));

while (pending.length) {
	const file = pending.pop();
	if (files.has(file)) continue;
	files.add(file);
	const entry = byFile.get(file);
	if (!entry) continue;
	for (const key of [...(entry.imports ?? []), ...(entry.dynamicImports ?? [])]) {
		const dep = manifest[key]?.file;
		if (dep && !(dep.includes('/nodes/') && !nodes.has(dep))) pending.push(dep);
	}
	pending.push(...(entry.css ?? []), ...(entry.assets ?? []));
}

// Fonts and images the page and its styles name from the site's root (static/).
const rooted = new Set();
const scan = (text) => {
	// "/fonts/read/inter.woff2" in the page; Vite makes the styles' "../../../fonts/read/inter.woff2".
	for (const m of text.matchAll(/["'(](?:\/|(?:\.\.\/)+)((?:fonts|ark-of-the-covenant)\/[^"')\s?#]+)/g)) rooted.add(m[1]);
	if (/["']\/favicon\.png["']/.test(text)) rooted.add('favicon.png');
};
scan(html);
for (const f of files) if (f.endsWith('.css') || f.endsWith('.js')) scan(readFileSync(join(client, f), 'utf8'));
for (const f of rooted) {
	// The page's prerendered data and the web's verses.json aren't needed: the app answers verses.json itself.
	if (f.endsWith('.json') || f.endsWith('og.jpg')) continue;
	if (existsSync(join(client, f))) files.add(f);
}

rmSync(out, { recursive: true, force: true });
let bytes = 0;
for (const f of [...files].sort()) {
	const from = f === PAGE ? join(pages, f) : join(client, f);
	if (!existsSync(from)) {
		console.error(`missing: ${f}`);
		process.exit(1);
	}
	mkdirSync(dirname(join(out, f)), { recursive: true });
	cpSync(from, join(out, f));
	bytes += statSync(from).size;
}
writeFileSync(
	join(out, 'README.md'),
	'Generated by site/scripts/app-web.mjs from the site\'s build: the Ark page the Mac app shows offline. Don\'t edit; rebuild.\n\n' +
		'The code is MIT. ark-of-the-covenant/ark.jpg, a render of the model, is CC BY 4.0 like the spec it comes from (objects/LICENSE).\n'
);
console.log(`${files.size} files, ${(bytes / 1024).toFixed(0)} KB, in ${relative(process.cwd(), out)}`);
for (const f of [...files].sort()) console.log(`  ${f}`);
