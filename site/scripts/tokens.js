// Writes the web reader's design tokens (src/lib/read/tokens.css) from the Mac app's token file,
// crates/app/assets/design-tokens.json, so both draw from one set of values. Run it after the
// token file changes; the output is committed.
//
//   node site/scripts/tokens.js
//
// Each theme is `html[data-read][data-theme=…]`; the four accents other than Ink are derived as
// crates/app/src/theme.rs derives them.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const tokens = JSON.parse(readFileSync(here('../../crates/app/assets/design-tokens.json'), 'utf8'));
const out = here('../src/lib/read/tokens.css');

const THEMES = ['light', 'sepia', 'dark'];
const ACCENTS = { oxblood: '#8E2B2B', forest: '#2F6B4F', plum: '#6B3F7A', graphite: '#4A4D55' };

/** `#RRGGBB` or `#RRGGBBAA` → a CSS colour. */
function css(hex) {
	const h = hex.replace('#', '');
	if (h.length === 6) return `#${h.toLowerCase()}`;
	const [r, g, b, a] = [0, 2, 4, 6].map((i) => parseInt(h.slice(i, i + 2), 16));
	return `rgb(${r} ${g} ${b} / ${+(a / 255).toFixed(3)})`;
}

const rgb = (hex) => [0, 2, 4].map((i) => parseInt(hex.replace('#', '').slice(i, i + 2), 16));
const hex = (c) => '#' + c.map((x) => x.toString(16).padStart(2, '0')).join('');
/** theme.rs `mix`: a toward b by t, each channel rounded. */
const mix = (a, b, t) => hex(rgb(a).map((x, i) => Math.round(x + (rgb(b)[i] - x) * t)));
/** theme.rs truncates the alpha to a byte. */
const alpha = (c, a) => `rgb(${rgb(c).join(' ')} / ${+(Math.floor(a * 255) / 255).toFixed(3)})`;

const kebab = (s) => s.replaceAll('_', '-');
const lines = [];
const block = (selector, vars) => {
	lines.push(`${selector} {`);
	for (const [k, v] of vars) lines.push(`\t--${k}: ${v};`);
	lines.push('}', '');
};

lines.push(
	'/* Generated by site/scripts/tokens.js from crates/app/assets/design-tokens.json. Do not edit. */',
	''
);

// Metrics and type: the same in every theme.
const t = tokens.type;
const fixed = [];
for (const [k, v] of Object.entries(tokens.space)) fixed.push([`space-${k}`, `${v}px`]);
for (const [k, v] of Object.entries(tokens.radius)) fixed.push([`radius-${k}`, `${v}px`]);
for (const [k, v] of Object.entries(tokens.size)) fixed.push([`size-${k}`, `${v}px`]);
for (const [k, v] of Object.entries(tokens.menu)) fixed.push([`menu-${kebab(k)}`, `${v}px`]);
for (const [k, v] of Object.entries(tokens.titlebar)) {
	if (typeof v === 'number') fixed.push([`titlebar-${kebab(k)}`, `${v}px`]);
}
for (const [name, s] of Object.entries(t.styles)) {
	const family = s.family === 'reading' ? 'var(--font-reading)' : 'var(--font-ui)';
	fixed.push([`type-${name}`, `${s.weight} ${s.size}px/${s.line_height}px ${family}`]);
	fixed.push([`type-${name}-tracking`, `${s.tracking_em}em`]);
}
const r = t.reading;
fixed.push(
	['font-reading', `${t.family.reading}, ${t.family.reading_fallback}, serif`],
	['font-ui', `${t.family.ui}, -apple-system, BlinkMacSystemFont, system-ui, sans-serif`],
	['reading-size', `${r.size_default}px`],
	['reading-line-height', `${r.line_height_ratio}`],
	['reading-measure', `${r.measure}px`],
	['paragraph-gap', `${r.paragraph_gap}px`],
	['first-line-indent', `${r.first_line_indent}px`],
	['poetry-indent', `${r.poetry_indent}px`],
	['stanza-gap', `${r.stanza_gap}px`],
	['verse-per-line-gutter', `${r.verse_per_line_gutter}px`],
	['verse-number-size', `${t.verse_number.size}px`],
	['verse-number-raise', `${t.verse_number.raise}px`],
	['verse-number-vpl-size', `${t.verse_number.verse_per_line.size}px`],
	['small-caps-scale', `${t.small_caps_lord.small_cap_size / t.small_caps_lord.cap_size}`],
	['small-caps-tracking', `${t.small_caps_lord.tracking_em}em`],
	['icon-stroke', `${tokens.icon.stroke['20']}`],
	['icon-stroke-sm', `${tokens.icon.stroke['16']}`],
	['disabled-opacity', `${tokens.state.disabled_opacity}`],
	['focus-ring-width', `${tokens.state.focus_ring_width}px`],
	['motion-fast', `${tokens.motion.fast_ms}ms`],
	['motion-base', `${tokens.motion.base_ms}ms`],
	['motion-slow', `${tokens.motion.slow_ms}ms`],
	['motion-easing', tokens.motion.easing],
	['verse-flash', `${tokens.motion.verse_flash_ms}ms`]
);
for (const [name, h] of Object.entries(tokens.color.highlight)) fixed.push([`swatch-${name}`, css(h.swatch)]);
block('html[data-read]', fixed);

// Colours per theme, then the accents.
for (const theme of THEMES) {
	const c = tokens.color[theme];
	const vars = Object.entries(c).map(([k, v]) => [kebab(k), css(v)]);
	for (const [name, h] of Object.entries(tokens.color.highlight)) vars.push([`hl-${name}`, css(h[theme])]);
	for (const [name, s] of Object.entries(tokens.shadow)) vars.push([`shadow-${name}`, s[theme].css]);
	const wash = theme === 'dark' ? 'dark' : 'light';
	vars.push(
		['hover-wash', css(tokens.state[`hover_wash_${wash}`])],
		['pressed-wash', css(tokens.state[`pressed_wash_${wash}`])]
	);
	// An element can show another theme's colours (the theme choices in the text popover and Settings).
	block(`html[data-read][data-theme='${theme}'],\nhtml[data-read] [data-theme-preview='${theme}']`, vars);
	for (const [accent, swatch] of Object.entries(ACCENTS)) {
		const dark = theme === 'dark';
		const a = dark ? mix(swatch, '#FFFFFF', 0.5) : swatch;
		const soft = mix(a, c.paper, dark ? 0.8 : 0.88);
		block(`html[data-read][data-theme='${theme}'][data-accent='${accent}']`, [
			['accent', a.toLowerCase()],
			['accent-soft', soft],
			['selection', alpha(a, dark ? 0.2 : 0.14)],
			['focus', alpha(a, dark ? 0.5 : 0.4)]
		]);
	}
}

lines.push(
	`/* Settings › Appearance shows each accent's swatch: the light theme's accent. */`,
	'html[data-read] {',
	`\t--accent-swatch-ink: ${css(tokens.color.light.accent)};`,
	...Object.entries(ACCENTS).map(([k, v]) => `\t--accent-swatch-${k}: ${css(v)};`),
	'}',
	''
);

writeFileSync(out, lines.join('\n'));
console.log(`wrote ${out}`);
